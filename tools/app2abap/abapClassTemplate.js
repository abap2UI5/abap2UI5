module.exports = function(className, formattedContent, sourcePath) {
    // The class name cannot carry the source path: ABAP object names are
    // capped at 30 characters (25 here, see MAX_CLASS_NAME_LENGTH in
    // trans2abap.js), so the folder is dropped and long basenames are
    // abbreviated via CLASS_NAME_STEMS. Name the source file in the header
    // instead - that is the way back from a class in the debugger to the
    // file to edit.
    if (!sourcePath) {
        throw new Error(`${className}: sourcePath is required for the generated header.`);
    }
    return `* =====================================================================
* GENERATED FILE - DO NOT EDIT (AGENTS.md rule 2)
* Source: app/webapp/${sourcePath}
* Embedded frontend resource, generated by tools/app2abap/trans2abap.js.
* Change the source file above and run 'npm run app2abap' to regenerate;
* the check_app2abap CI gate fails any manual edit here.
* =====================================================================
CLASS ${className} DEFINITION
  PUBLIC
  FINAL
  CREATE PUBLIC .

  PUBLIC SECTION.

    CLASS-METHODS get
      RETURNING
        VALUE(result) TYPE string.

  PROTECTED SECTION.
  PRIVATE SECTION.
ENDCLASS.


CLASS ${className} IMPLEMENTATION.

  METHOD get.

    result = ${formattedContent}
              \`\`.

  ENDMETHOD.

ENDCLASS.
`;
};
